/**
 * Returns a random Hadith from the collection.
 */
export function getRandomHadith(category = null) {
  const pool = category && category !== 'All'
    ? HADITH_COLLECTION.filter((h) => h.category === category)
    : HADITH_COLLECTION

  const list = pool.length > 0 ? pool : HADITH_COLLECTION
  const index = Math.floor(Math.random() * list.length)
  return list[index]
}

/**
 * Returns a stable Hadith of the day based on the calendar day of the year.
 */
export function getHadithOfTheDay(date = new Date()) {
  const start = new Date(date.getFullYear(), 0, 0)
  const diff = date - start
  const oneDay = 1000 * 60 * 60 * 24
  const dayOfYear = Math.floor(diff / oneDay)
  const index = Math.abs(dayOfYear) % HADITH_COLLECTION.length
  return HADITH_COLLECTION[index]
}

/**
 * Returns a Hadith by its specific numerical ID.
 */
export function getHadithById(id) {
  return HADITH_COLLECTION.find((h) => h.id === id) || HADITH_COLLECTION[0]
}
